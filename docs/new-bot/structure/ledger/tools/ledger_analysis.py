NO_ENTRY_FROM, FLATTEN_AT, REOPEN = 12 * 60 + 55, 13 * 60 + 5, 15 * 60
import datetime as _D
from zoneinfo import ZoneInfo as _Z
_PT = _Z('America/Los_Angeles')
def eod_cut(T):   # the TradeDay's 13:05 PT
    d = _D.datetime.fromtimestamp(T + 9 * 3600, _PT).date()
    return int(_D.datetime(d.year, d.month, d.day, FLATTEN_AT // 60, FLATTEN_AT % 60, tzinfo=_PT).timestamp())
def jx(x, eod): return bisect.bisect_left(m1t, eod_cut(x['T'])) if eod else len(m1)
def end_px(x, j, eod):   # the 13:05 bar's open (eod), else the last close
    if eod and j < len(m1) and m1[j]['t'] == eod_cut(x['T']): return m1[j]['o']
    return m1[j - 1]['c']
def session_closed(T):   # SESSION_CLOSE: no new entries 12:55 -> 15:00 PT (T = the decision minute)
    m = ptmin(T); return NO_ENTRY_FROM <= m < REOPEN
def r2exit(x, eod=False):
    """risk.py r2exit, verbatim except the bar window (eod)."""
    d, e, s = x['d'], x['entry'], x['stop']; R_ = abs(e - s); t1, t2 = e + d * R_, e + d * 2 * R_
    i = bisect.bisect_left(m1t, x['T']); tp1 = False; j = jx(x, eod)
    for b in m1[i:j]:
        m = ptmin(b['t'])
        if 840 <= m < 900:
            mtm = (b['o'] - e) * d / R_
            return (2 / 3 + max(0.0, min(2, mtm)) / 3) if tp1 else max(-1.0, min(2.0, mtm))
        hi_fav = (b['h'] - e) * d if d > 0 else (e - b['l'])
        lo_adv = (e - b['l']) if d > 0 else (b['h'] - e)
        if not tp1:
            if lo_adv >= R_: return -1.0
            if hi_fav >= R_:
                tp1 = True
                if hi_fav >= 2 * R_: return 2 / 3 + 2 / 3
            continue
        if lo_adv >= 0: return 2 / 3
        if hi_fav >= 2 * R_: return 2 / 3 + 2 / 3
    mtm = (end_px(x, j, eod) - e) * d / R_
    return (2 / 3 + max(0.0, min(2, mtm)) / 3) if tp1 else max(-1.0, min(2.0, mtm))

# ---------------------------------------------------------------- risk_int.py (verbatim, plus the eod bar window)
def parts(x, eod=False):
    """(tp1_hit, runner_R, full_R): same path logic as risk.r2exit."""
    d, e, s = x['d'], x['entry'], x['stop']; Rr = abs(e - s); i = bisect.bisect_left(m1t, x['T']); tp1 = False; j = jx(x, eod)
    for b in m1[i:j]:
        m = ptmin(b['t'])
        if 840 <= m < 900:
            mtm = (b['o'] - e) * d / Rr
            return (True, max(0.0, min(2, mtm)), None) if tp1 else (False, None, max(-1.0, min(2.0, mtm)))
        hi = (b['h'] - e) * d if d > 0 else (e - b['l']); lo = (e - b['l']) if d > 0 else (b['h'] - e)
        if not tp1:
            if lo >= Rr: return (False, None, -1.0)
            if hi >= Rr:
                tp1 = True
                if hi >= 2 * Rr: return (True, 2.0, None)
            continue
        if lo >= 0: return (True, 0.0, None)
        if hi >= 2 * Rr: return (True, 2.0, None)
    mtm = (end_px(x, j, eod) - e) * d / Rr
    return (True, max(0.0, min(2, mtm)), None) if tp1 else (False, None, max(-1.0, min(2.0, mtm)))

def pcount(n): return max(1, min(n - 1, round(n * 2 / 3 + 1e-9))) if n >= 2 else 0

def usd_int(x, dollars, r):
    ctr = max(1, int(dollars // (x['R'] * R.PT_USD))); risk = ctr * x['R'] * R.PT_USD
    if r == 0: return 0.0, risk
    tp1, run, full = r
    if not tp1: rm = ctr * full
    else: k = pcount(ctr); rm = k * 1.0 + (ctr - k) * run
    return rm * x['R'] * R.PT_USD - ctr * 2 * R.COST_SIDE, risk

# ---------------------------------------------------------------- same walk, exit time + path label only
def exit_time(x, eod=False):
    d, e, s = x['d'], x['entry'], x['stop']; Rr = abs(e - s); i = bisect.bisect_left(m1t, x['T']); tp1 = False; j = jx(x, eod)
    for b in m1[i:j]:
        m = ptmin(b['t'])
        if 840 <= m < 900: return b['t'], 'mtm 14:00' + (' after TP1' if tp1 else '')
        hi = (b['h'] - e) * d if d > 0 else (e - b['l']); lo = (e - b['l']) if d > 0 else (b['h'] - e)
        if not tp1:
            if lo >= Rr: return b['t'] + 60, 'stop'
            if hi >= Rr:
                tp1 = True
                if hi >= 2 * Rr: return b['t'] + 60, 'TP1+2R same bar'
            continue
        if lo >= 0: return b['t'] + 60, 'TP1 then BE'
        if hi >= 2 * Rr: return b['t'] + 60, 'TP1 then 2R'
    return (eod_cut(x['T']) if eod and j < len(m1) else m1[j - 1]['t'] + 60, ('flat 13:05' if eod and j < len(m1) else 'data end (MTM)') + (' after TP1' if tp1 else ''))

# ---------------------------------------------------------------- r3.2: the REAL exit plan (money planExits, computed in run-ledger.cjs)
def real_exit(x, pl, eod=True, mode='cons'):
    """TP1 partial (pl tp1Qty at tp1) -> stop to beStop -> the rest at TP2; 1-lot: no TP1 order, its TP1 price moves the stop to BE.
    Flat at the 13:05 PT bar's open (eod), data end = last close. Whole contracts, $2/pt, $0.62/side.
    Intrabar ambiguity (MacDot 6623683046 item 1): a 1m bar whose OHLC cannot order two events is flagged, and the trade is run both ways:
      before TP1, a bar touching the stop AND TP1: cons = stop first, opt = TP1 first;
      on the TP1 bar, the BE stop also touched: cons = TP1 then BE (rest out at BE), opt = no BE this bar (TP2 if reached);
      after TP1, a bar touching BE/stop AND TP2: cons = stop first, opt = TP2 first.
    (TP1 and TP2 on one bar is not ambiguous: TP2 lies beyond TP1.)"""
    if not pl: return None
    d, e, n = x['d'], x['entry'], pl['contracts']; stop = x['stop']; tp1, q1, tp2, be = pl['tp1'], pl['tp1Qty'], pl['tp2'], pl['beStop']
    i = bisect.bisect_left(m1t, x['T']); done1 = False; left = n; pnl = 0.0; path = None; j = jx(x, eod); amb = []; cons = mode == 'cons'
    fav = lambda b, px: (b['l'] <= px) if d < 0 else (b['h'] >= px)
    adv = lambda b, px: (b['h'] >= px) if d < 0 else (b['l'] <= px)
    def out(px, why):
        nonlocal pnl, left, path
        pnl += left * (px - e) * d; left = 0; path = why
    for b in m1[i:j]:
        m = ptmin(b['t'])
        if 840 <= m < 900: out(b['o'], 'MTM 14:00' + (' after TP1' if done1 else '')); break
        if not done1:
            hs, h1 = adv(b, stop), fav(b, tp1)
            if hs and h1: amb.append(b['t'])
            if hs and (cons or not h1): out(stop, 'stop'); break
            if not h1: continue
            done1 = True
            if q1 > 0: pnl += q1 * (tp1 - e) * d; left -= q1
            if be is not None and (be - stop) * d > 0: stop = be
            h2, hb = fav(b, tp2), adv(b, stop)
            if hb: amb.append(b['t'])
            if hb and cons: out(stop, 'TP1 then BE (same bar)'); break
            if h2: out(tp2, 'TP1+TP2 same bar'); break
            continue
        hs, h2 = adv(b, stop), fav(b, tp2)
        if hs and h2: amb.append(b['t'])
        if hs and (cons or not h2): out(stop, 'BE stop after TP1'); break
        if h2: out(tp2, 'TP1 then TP2'); break
    if left: out(end_px(x, j, eod), ('flat 13:05' if eod and j < len(m1) else 'data end (MTM)') + (' after TP1' if done1 else ''))
    usd = pnl * R.PT_USD - n * 2 * R.COST_SIDE; risk = n * x['R'] * R.PT_USD
    return dict(usd=round(usd, 2), R=round(usd / risk, 4), path=path, contracts=n, ambiguous=sorted(set(amb)))

def real_both(x, pl):
    c, o = real_exit(x, pl, True, 'cons'), real_exit(x, pl, True, 'opt')
    if not c: return None
    return dict(usd=c['usd'], R=c['R'], path=c['path'], usd_opt=o['usd'], R_opt=o['R'], path_opt=o['path'], ambiguous=sorted(set(c['ambiguous']) | set(o['ambiguous'])), contracts=c['contracts'])

def outcome(x, grade):
    p = parts(x); r2 = R.r2exit(x); xt, path = exit_time(x)
    assert abs(r2exit(x) - r2) < 1e-12   # the local copy is the verbatim risk.py r2exit
    pe = parts(x, True); r2e = r2exit(x, True); xte, pathe = exit_time(x, True); u450e, k450e = usd_int(x, FLAT, pe)
    ctr450 = max(1, int(FLAT // (x['R'] * R.PT_USD))); u450, k450 = usd_int(x, FLAT, p)
    gd = GRADE_USD.get(grade); ctrG = max(1, int(gd // (x['R'] * R.PT_USD))) if gd else None
    uG, kG = usd_int(x, gd, p) if gd else (None, None)
    rint = lambda u, k: None if u is None else round(u / k, 4)   # net $ / $ risked = whole-contract R after costs
    uGe = usd_int(x, gd, pe)[0] if gd else None
    return dict(usdG_eod=None if uGe is None else round(uGe, 2), r2R_eod=round(r2e, 4), path_eod=pathe, exitT_eod=xte, usd450_eod=round(u450e, 2), R450_eod=rint(u450e, k450e), crossed1400=path != pathe or abs(r2 - r2e) > 1e-9,
                r2R=round(r2, 4), path=path, exitT=xt, ctr450=ctr450, risk450=round(k450, 2), usd450=round(u450, 2), R450=rint(u450, k450),
                ctrG=ctrG, riskG=None if kG is None else round(kG, 2), usdG=None if uG is None else round(uG, 2), RG=rint(uG, kG))

